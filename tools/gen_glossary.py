"""Write the glossary in ``docs/USER-GUIDE.md`` from ``hermes_signalbox.labels``.

    python tools/gen_glossary.py            rewrite the block between the glossary markers
    python tools/gen_glossary.py --check    exit 1 when the guide is out of date (used by the tests)

The labels are what the chat replies, the command-line text and the dashboard show, so the published glossary
is generated from them instead of being written a second time.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from hermes_signalbox import labels

GUIDE = Path(__file__).resolve().parents[1] / "docs" / "USER-GUIDE.md"
START = "<!-- glossary:start (generated by tools/gen_glossary.py; do not edit by hand) -->"
END = "<!-- glossary:end -->"

# group key in labels.glossary() -> (heading, what the first column is)
GROUPS = {
    "capabilities": ("Permissions", "Capability"),
    "statuses": ("Module states", "State"),
    "modes": ("Start modes", "Mode"),
    "severities": ("Notice severities", "Severity"),
    "actors": ("Who did it", "Actor"),
    "actions": ("Audit log actions", "Action"),
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    """The glossary as Markdown: one table per group, in the order of ``GROUPS``."""
    glossary = labels.glossary()
    missing = sorted(set(glossary) - set(GROUPS))
    if missing:
        raise SystemExit(f"gen_glossary: no heading for label group(s) {missing}")
    parts = []
    for key, (heading, column) in GROUPS.items():
        rows = [f"### {heading}", "", f"| {column} | Shown as | Meaning |", "|---|---|---|"]
        rows += [
            f"| `{name}` | {_cell(entry['label'])} | {_cell(entry['meaning'])} |"
            for name, entry in glossary[key].items()
        ]
        parts.append("\n".join(rows))
    return "\n\n".join(parts)


def current(text: str) -> str:
    """The glossary block now in the guide text."""
    if START not in text or END not in text:
        raise SystemExit("gen_glossary: the glossary markers are missing from the guide")
    return text.split(START, 1)[1].split(END, 1)[0].strip("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 when out of date")
    parser.add_argument("--file", type=Path, default=GUIDE, help="guide file (default: docs/USER-GUIDE.md)")
    args = parser.parse_args(argv)
    text = args.file.read_text(encoding="utf-8")
    want = render()
    if current(text) == want:
        return 0
    if args.check:
        print(f"gen_glossary: {args.file.name} is out of date; run python tools/gen_glossary.py")
        return 1
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    args.file.write_text(f"{head}{START}\n{want}\n{END}{tail}", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
